package net.linlan.dsh.ontology.engine.validation;

import com.fasterxml.jackson.databind.ObjectMapper;
import net.linlan.dsh.ontology.engine.loader.ModelLoader;
import net.linlan.dsh.ontology.engine.registry.OntologyRegistry;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;

import java.util.HashMap;
import java.util.List;
import java.util.Map;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

/** 0.2.2 T3.1：写库前字段校验覆盖必填、类型、枚举、未知字段、部分更新与开关。 */
class SchemaValidatorTest {

    private static OntologyRegistry registry;

    @BeforeAll
    static void loadModels() {
        registry = OntologyRegistry.from(
                new ModelLoader(SchemaValidatorTest.class.getClassLoader(), new ObjectMapper()).load().descriptors());
    }

    private static SchemaValidator validator(boolean enabled, String policy) {
        return new SchemaValidator(registry, enabled, policy);
    }

    @Test
    void required_field_missing_is_violation() {
        List<FieldViolation> violations = validator(true, "warn").validate("country", Map.of("iso_code", "CN"), false);
        assertTrue(violations.stream().anyMatch(v -> "required".equals(v.rule()) && "name".equals(v.field())));
    }

    @Test
    void required_field_blank_is_violation() {
        List<FieldViolation> violations = validator(true, "warn")
                .validate("country", Map.of("name", "   "), false);
        assertTrue(violations.stream().anyMatch(v -> "required".equals(v.rule()) && "name".equals(v.field())));
    }

    @Test
    void autogenerated_id_may_be_absent() {
        List<FieldViolation> violations = validator(true, "warn").validate("country", Map.of("name", "中国"), false);
        assertTrue(violations.isEmpty(), () -> "主键缺省不应报错: " + violations);
    }

    @Test
    void explicit_invalid_id_type_is_violation() {
        List<FieldViolation> violations = validator(true, "warn")
                .validate("country", Map.of("id", "abc", "name", "中国"), false);
        assertTrue(violations.stream().anyMatch(v -> "type".equals(v.rule()) && "id".equals(v.field())));
    }

    @Test
    void integer_field_rejects_decimal() {
        List<FieldViolation> violations = validator(true, "warn")
                .validate("hotspot", Map.of("hotspot_name", "热点", "heat_score", 1.5), false);
        assertTrue(violations.stream().anyMatch(v -> "type".equals(v.rule()) && "heatScore".equals(v.field())));
    }

    @Test
    void boolean_field_rejects_arbitrary_text() {
        var flagDescriptor = new net.linlan.dsh.ontology.engine.model.AggregateDescriptor(
                "AGG-FLAG", "标记", "OntologyFlag", "flag",
                List.of(), List.of(),
                List.of(new net.linlan.dsh.ontology.engine.model.AttributeDescriptor(
                        "enabled", "启用", "Boolean", false, false, List.of(), null, null, "test")),
                List.of(), "test.yaml");
        SchemaValidator flagValidator = new SchemaValidator(
                OntologyRegistry.from(List.of(flagDescriptor)), true, "warn");
        List<FieldViolation> violations = flagValidator.validate("flag", Map.of("enabled", "yes"), false);
        assertTrue(violations.stream().anyMatch(v -> "type".equals(v.rule()) && "enabled".equals(v.field())));
    }

    @Test
    void enum_field_rejects_unknown_value() {
        List<FieldViolation> violations = validator(true, "warn")
                .validate("hotspot", Map.of("hotspot_name", "热点", "risk_level", "severe"), false);
        assertTrue(violations.stream().anyMatch(v -> "enum".equals(v.rule()) && "riskLevel".equals(v.field())));
    }

    @Test
    void enum_field_accepts_known_value() {
        List<FieldViolation> violations = validator(true, "warn")
                .validate("hotspot", Map.of("hotspot_name", "热点", "risk_level", "high"), false);
        assertTrue(violations.isEmpty(), () -> "合法枚举不应报错: " + violations);
    }

    @Test
    void snake_case_keys_are_resolved_to_model_fields() {
        Map<String, Object> data = new HashMap<>();
        data.put("name", "中国");
        data.put("iso_code", "CN");
        List<FieldViolation> violations = validator(true, "reject").validate("country", data, false);
        assertTrue(violations.isEmpty(), () -> "snake_case 应对齐模型字段: " + violations);
    }

    @Test
    void unknown_field_is_warning_by_default() {
        List<FieldViolation> violations = validator(true, "warn")
                .validate("country", Map.of("name", "中国", "status", 1), false);
        assertTrue(violations.isEmpty(), () -> "warn 策略不应产生错误: " + violations);
    }

    @Test
    void unknown_field_policy_reject_marks_violation() {
        List<FieldViolation> violations = validator(true, "reject")
                .validate("country", Map.of("name", "中国", "status", 1), false);
        assertTrue(violations.stream().anyMatch(v -> "unknown".equals(v.rule()) && "status".equals(v.field())));
    }

    @Test
    void partial_update_ignores_unsubmitted_required_fields() {
        List<FieldViolation> violations = validator(true, "warn")
                .validate("country", Map.of("name", "中国更新"), true);
        assertTrue(violations.isEmpty(), () -> "部分更新不应校验未提交字段: " + violations);
    }

    @Test
    void disabled_validator_returns_empty_list() {
        assertTrue(validator(false, "reject").validate("country", Map.of(), false).isEmpty());
    }

    @Test
    void unknown_category_is_rejected() {
        IllegalArgumentException exception = assertThrows(IllegalArgumentException.class,
                () -> validator(true, "warn").validate("not-a-type", Map.of(), false));
        assertEquals("未知本体类型: not-a-type", exception.getMessage());
    }
}
